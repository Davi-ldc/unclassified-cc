import { encodeParameterSchema, hasParameterAliases, parameterKey, renameInputKeys } from './parameter-profile.js'

export const NEUTRAL_PROFILE_ID = 'neutral-v1'
export const NEUTRAL_V2_PROFILE_ID = 'neutral-v2'
export type WireProfileId = typeof NEUTRAL_PROFILE_ID | typeof NEUTRAL_V2_PROFILE_ID

export interface WireCodec {
  readonly profileId: string
  encodeTool(name: string): string
  decodeTool(name: string): string
  encodeSelector(domain: 'agent' | 'skill' | 'tool', name: string): string
  decodeSelector(domain: 'agent' | 'skill' | 'tool', name: string): string
  encodeInputKey(nativeTool: string, key: string): string
  decodeInputKey(nativeTool: string, key: string): string
  encodeToolSchema(nativeTool: string, schema: unknown): unknown
  translateInput(nativeTool: string, input: unknown, direction: 'encode' | 'decode'): unknown
  rewriteInstruction(text: string): string
  needsInputTranslation(nativeTool: string): boolean
  readonly active: boolean
}

export const TOOL_ALIASES = Object.freeze({
  Agent: 'delegate',
  AskUserQuestion: 'ask_user',
  Bash: 'shell',
  CronCreate: 'schedule_job',
  CronDelete: 'cancel_job',
  CronList: 'list_jobs',
  Edit: 'edit_file',
  EnterPlanMode: 'begin_planning',
  EnterWorktree: 'enter_workspace',
  ExitPlanMode: 'finish_planning',
  ExitWorktree: 'leave_workspace',
  ListAgents: 'list_agents',
  NotebookEdit: 'edit_notebook',
  Read: 'read_file',
  ReportFindings: 'report_findings',
  ScheduleWakeup: 'schedule_wakeup',
  SendMessage: 'send_message',
  Skill: 'load_skill',
  TaskStop: 'stop_task',
  WebFetch: 'fetch_url',
  WebSearch: 'search_web',
  Workflow: 'run_workflow',
  Write: 'write_file',
} as const)

const AGENT_ALIASES = Object.freeze({
  claude: 'assistant',
  'claude-code-guide': 'client-guide',
  Explore: 'explorer',
  Plan: 'planner',
})
const SKILL_PREFIX = 'anthropic-skills:'
const WIRE_SKILL_PREFIX = 'standard:'
const AMBIGUOUS_TOOL_WORDS = new Set(['Agent', 'Edit', 'Read', 'Skill', 'Workflow', 'Write'])
type RecordValue = Record<string, unknown>
type SelectorDomain = 'agent' | 'skill' | 'tool'

export class WireProfileError extends Error {
  readonly status = 400
}

function record(value: unknown): value is RecordValue {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

function clientTool(value: RecordValue): boolean {
  return !Object.hasOwn(value, 'type') || value.type === 'custom'
}

function textBlocks(value: unknown): string[] {
  if (typeof value === 'string') return [value]
  if (!Array.isArray(value)) return []
  return value.flatMap(block => record(block) && block.type === 'text' && typeof block.text === 'string' ? [block.text] : [])
}

// Catalog headers and entries are generated by the client. Other prose does not register selectors.
function catalogHeader(line: string): 'agent' | 'skill' | undefined {
  const header = line.replace(/^#{1,6}\s+/, '').trim()
  if (/^(?:Available agent types(?: for (?:the )?Agent tool)?|The following agent types are available):$/.test(header)) return 'agent'
  if (/^(?:Available skills|The following skills are available(?: for use with (?:the )?Skill tool)?):$/.test(header)) return 'skill'
  return undefined
}

function catalogEntries(text: string, visit: (domain: 'agent' | 'skill', name: string) => string): string {
  let domain: 'agent' | 'skill' | undefined
  return text.split('\n').map(line => {
    const header = catalogHeader(line)
    if (header) {
      domain = header
      return line
    }
    if (/^(?:#{1,6}\s|<\/?[a-z-]+>)/.test(line.trim())) domain = undefined
    if (!domain) return line
    const entry = /^(\s*[-*]\s+)(`?)([A-Za-z0-9_.-]+(?::[A-Za-z0-9_.-]+)*)(\2:\s)/.exec(line)
    if (!entry) {
      if (line.trim() && !/^\s/.test(line)) domain = undefined
      return line
    }
    const name = visit(domain, entry[3])
    return name === entry[3] ? line : entry[1] + entry[2] + name + entry[4] + line.slice(entry[0].length)
  }).join('\n')
}

function escapePattern(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function inPath(text: string, start: number, length: number): boolean {
  const before = text.slice(Math.max(0, start - 128), start)
  const after = text.slice(start + length, start + length + 128)
  if (/[\w$/\\@-]$/.test(before) || /^[\w$/\\@-]/.test(after)) return true
  if (/\.[\w]/.test(after.slice(0, 2))) return true
  if (/[.:]$/.test(before) && !/(?:^|[\s`(])functions\.$/.test(before)) return true
  return false
}

function toolReference(text: string, start: number, name: string): boolean {
  const before = text.slice(Math.max(0, start - 128), start)
  const after = text.slice(start + name.length, start + name.length + 128)
  if (inPath(text, start, name.length)) return false
  if (!AMBIGUOUS_TOOL_WORDS.has(name)) return true
  return (/`$/.test(before) && /^`/.test(after))
    || /^\s*\(/.test(after)
    || /functions\.$/.test(before)
    || /^\s+tools?\b/i.test(after)
    || /\b(?:use|using|call|calling|invoke|invoking|via|with)\s+(?:the\s+)?$/i.test(before)
    || /\btools?\s*[:=]\s*['"]?$/i.test(before)
}

function replaceField(input: RecordValue, key: string, translate: (value: string) => string): RecordValue {
  const value = input[key]
  if (typeof value !== 'string') return input
  const replacement = translate(value)
  return replacement === value ? input : { ...input, [key]: replacement }
}

export function createWireCodec(request: unknown, profileId: WireProfileId = NEUTRAL_PROFILE_ID): WireCodec {
  if (profileId !== NEUTRAL_PROFILE_ID && profileId !== NEUTRAL_V2_PROFILE_ID) throw new WireProfileError(`Unknown wire profile: ${profileId}`)
  const occupied = new Set<string>()
  const candidates = new Set<string>()
  const providerNames = new Set<string>()
  const definitions = new Map<string, RecordValue>()
  const selectors = { agent: new Set<string>(), skill: new Set<string>() }
  const catalogTexts: string[] = []
  if (record(request)) {
    if (Array.isArray(request.tools)) {
      for (const tool of request.tools) {
        if (!record(tool) || typeof tool.name !== 'string') continue
        occupied.add(tool.name)
        if (!clientTool(tool)) {
          providerNames.add(tool.name)
          continue
        }
        if (definitions.has(tool.name)) throw new WireProfileError(`Duplicate client tool name: ${tool.name}`)
        definitions.set(tool.name, tool)
        candidates.add(tool.name)
        if (tool.name !== 'Agent' && tool.name !== 'Skill') continue
        if (typeof tool.description === 'string') catalogTexts.push(tool.description)
        const domain = tool.name === 'Agent' ? 'agent' : 'skill'
        const field = domain === 'agent' ? 'subagent_type' : 'skill'
        const schema = record(tool.input_schema) ? tool.input_schema : undefined
        const propertyValue = schema?.properties
        const properties = record(propertyValue) ? propertyValue : undefined
        const selectorValue = properties?.[field]
        const selector = record(selectorValue) ? selectorValue : undefined
        if (Array.isArray(selector?.enum)) {
          for (const name of selector.enum) if (typeof name === 'string') selectors[domain].add(name)
        }
      }
    }
    catalogTexts.push(...textBlocks(request.system))
    if (Array.isArray(request.messages)) {
      for (const message of request.messages) {
        if (!record(message)) continue
        if (message.role === 'system') catalogTexts.push(...textBlocks(message.content))
        if (message.role === 'user') {
          for (const text of textBlocks(message.content)) {
            if (/^<system-reminder>\s*\n(?:Available agent types|The following skills are available|Available skills)/.test(text)
              && text.trimEnd().endsWith('</system-reminder>')) catalogTexts.push(text)
          }
        }
        if (message.role !== 'assistant' || !Array.isArray(message.content)) continue
        for (const block of message.content) {
          if (!record(block) || block.type !== 'tool_use' || typeof block.name !== 'string') continue
          occupied.add(block.name)
          candidates.add(block.name)
          if (!record(block.input)) continue
          if (block.name === 'Agent' && typeof block.input.subagent_type === 'string') selectors.agent.add(block.input.subagent_type)
          if (block.name === 'Skill' && typeof block.input.skill === 'string') selectors.skill.add(block.input.skill)
        }
      }
    }
  }
  for (const name of providerNames) {
    if (definitions.has(name)) throw new WireProfileError(`Ambiguous client and provider tool name: ${name}`)
    candidates.delete(name)
  }
  for (const text of catalogTexts) catalogEntries(text, (domain, name) => { selectors[domain].add(name); return name })

  // Only these closures can reach the maps; freezing a Map would not prevent set/delete.
  const forward = new Map<string, string>()
  const reverse = new Map<string, string>()
  for (const [native, alias] of Object.entries(TOOL_ALIASES)) {
    if (!candidates.has(native)) continue
    if (occupied.has(alias)) throw new WireProfileError(`Tool alias collision: ${native} -> ${alias}`)
    forward.set(native, alias)
    reverse.set(alias, native)
  }
  const agentForward = new Map<string, string>()
  const agentReverse = new Map<string, string>()
  if (forward.has('Agent')) {
    for (const [native, alias] of Object.entries(AGENT_ALIASES)) {
      if (selectors.agent.has(alias)) throw new WireProfileError(`Agent selector alias collision: ${native} -> ${alias}`)
      agentForward.set(native, alias)
      agentReverse.set(alias, native)
    }
  }
  const skillActive = forward.has('Skill')
  if (skillActive) {
    for (const name of selectors.skill) {
      if (name === 'model-api' || name.startsWith(WIRE_SKILL_PREFIX)) throw new WireProfileError(`Skill selector alias collision: ${name}`)
    }
  }
  const active = forward.size > 0
  const encodeTool = (name: string): string => forward.get(name) ?? name
  const decodeTool = (name: string): string => reverse.get(name) ?? name
  function encodeSelector(domain: SelectorDomain, name: string): string {
    if (domain === 'tool') return encodeTool(name)
    if (domain === 'agent') return agentForward.get(name) ?? name
    if (!skillActive) return name
    if (name === 'claude-api') return 'model-api'
    return name.startsWith(SKILL_PREFIX) && name.length > SKILL_PREFIX.length ? WIRE_SKILL_PREFIX + name.slice(SKILL_PREFIX.length) : name
  }
  function decodeSelector(domain: SelectorDomain, name: string): string {
    if (domain === 'tool') return decodeTool(name)
    if (domain === 'agent') return agentReverse.get(name) ?? name
    if (!skillActive) return name
    if (name === 'model-api') return 'claude-api'
    return name.startsWith(WIRE_SKILL_PREFIX) && name.length > WIRE_SKILL_PREFIX.length ? SKILL_PREFIX + name.slice(WIRE_SKILL_PREFIX.length) : name
  }
  function encodeInputKey(nativeTool: string, key: string): string {
    if (profileId !== NEUTRAL_V2_PROFILE_ID || !forward.has(nativeTool)) return key
    if (parameterKey(nativeTool, key, 'decode') !== key) throw new WireProfileError(`Parameter alias collision: reserved wire key ${key} for ${nativeTool}`)
    return parameterKey(nativeTool, key, 'encode')
  }
  function decodeInputKey(nativeTool: string, key: string): string {
    if (profileId !== NEUTRAL_V2_PROFILE_ID || !forward.has(nativeTool)) return key
    if (parameterKey(nativeTool, key, 'encode') !== key) throw new WireProfileError(`Parameter alias collision: reserved native key ${key} for ${nativeTool}`)
    return parameterKey(nativeTool, key, 'decode')
  }
  const reject = (message: string): never => { throw new WireProfileError(message) }
  function encodeToolSchema(nativeTool: string, schema: unknown): unknown {
    if (profileId !== NEUTRAL_V2_PROFILE_ID || !forward.has(nativeTool)) return schema
    return encodeParameterSchema(nativeTool, schema, {
      encodeKey: key => encodeInputKey(nativeTool, key), encodeSelector, decodeSelector, rewriteInstruction, reject,
    })
  }
  function needsInputTranslation(nativeTool: string): boolean {
    return forward.has(nativeTool) && (nativeTool === 'Agent' || nativeTool === 'Skill' || nativeTool === 'ExitPlanMode'
      || (profileId === NEUTRAL_V2_PROFILE_ID && hasParameterAliases(nativeTool)))
  }
  function translateSelectors(nativeTool: string, input: RecordValue, direction: 'encode' | 'decode'): RecordValue {
    const translate = direction === 'encode' ? encodeSelector : decodeSelector
    if (nativeTool === 'Agent') return replaceField(input, 'subagent_type', value => translate('agent', value))
    if (nativeTool === 'Skill') return replaceField(input, 'skill', value => translate('skill', value))
    if (nativeTool !== 'ExitPlanMode' || !Array.isArray(input.allowedPrompts)) return input
    let changed = false
    const allowedPrompts = input.allowedPrompts.map(prompt => {
      const replacement = record(prompt) ? replaceField(prompt, 'tool', value => translate('tool', value)) : prompt
      if (replacement !== prompt) changed = true
      return replacement
    })
    return changed ? { ...input, allowedPrompts } : input
  }
  function translateInput(nativeTool: string, input: unknown, direction: 'encode' | 'decode'): unknown {
    if (!needsInputTranslation(nativeTool) || !record(input)) return input
    if (profileId !== NEUTRAL_V2_PROFILE_ID) return translateSelectors(nativeTool, input, direction)
    if (direction === 'encode') {
      return renameInputKeys(translateSelectors(nativeTool, input, direction), key => encodeInputKey(nativeTool, key), reject)
    }
    return translateSelectors(nativeTool, renameInputKeys(input, key => decodeInputKey(nativeTool, key), reject), direction)
  }
  const toolPattern = forward.size ? new RegExp(`\\b(?:${[...forward.keys()].map(escapePattern).join('|')})\\b`, 'g') : undefined
  function rewriteInstruction(text: string): string {
    if (!active) return text
    let output = catalogEntries(text, encodeSelector)
    output = output.replace(/\b(?:Claude Code|Claude Agent SDK)\b/g, (brand: string, start: number, source: string) => {
      if (inPath(source, start, brand.length)) return brand
      return brand === 'Claude Code' ? 'the coding client' : 'the agent runtime'
    })
    const clientPhrases: Record<string, string> = {
      'Claude session': 'client session',
      'Claude sessions': 'client sessions',
      'when Claude exits': 'when the client exits',
      'not that its Claude read it': 'not that its agent read it',
    }
    output = output.replace(/\b(?:Claude sessions?|when Claude exits|not that its Claude read it)\b/g,
      (match: string, start: number, source: string) => inPath(source, start, match.length) ? match : clientPhrases[match])
    output = output.replace(/(\bsubagent_type["']?\s*[:=]\s*["'])([^"'\n]+)(["'])/g,
      (_match, prefix: string, name: string, suffix: string) => prefix + encodeSelector('agent', name) + suffix)
    output = output.replace(/(\bskill["']?\s*[:=]\s*["'])([^"'\n]+)(["'])/g,
      (_match, prefix: string, name: string, suffix: string) => prefix + encodeSelector('skill', name) + suffix)
    output = output.replace(/(`?)(claude-code-guide|claude|Explore|Plan|claude-api|anthropic-skills:[A-Za-z0-9_.-]+)(\1)(\s+(?:agent|subagent|skill)\b)/g,
      (match: string, quote: string, name: string, _closing: string, kind: string, start: number, source: string) => {
        if (inPath(source, start + quote.length, name.length)) return match
        const domain = /skill\b/.test(kind) ? 'skill' : 'agent'
        return quote + encodeSelector(domain, name) + quote + kind
      })
    if (toolPattern) output = output.replace(toolPattern, (name: string, start: number, source: string) => toolReference(source, start, name) ? encodeTool(name) : name)
    return output
  }
  return Object.freeze({ profileId, active, encodeTool, decodeTool, encodeSelector, decodeSelector, encodeInputKey, decodeInputKey, encodeToolSchema, translateInput, needsInputTranslation, rewriteInstruction })
}
